using System;
using System.Linq;
using System.Threading.Tasks;
using AssistenciaTech.Models;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.DependencyInjection;
using Microsoft.Extensions.Logging;

namespace AssistenciaTech.Data
{
    /// <summary>
    /// Inicializador formal do banco de dados (EnsureCreated + Schema Updates idempotentes + Seed de usuários).
    /// Projetado para suportar ambientes com PgBouncer Transaction Pooling (ex: Neon Pooler no Render).
    /// </summary>
    public static class DbInitializer
    {
        public static async Task InitializeAsync(IServiceProvider rootProvider)
        {
            using var scope = rootProvider.CreateScope();
            var services = scope.ServiceProvider;
            var logger = services.GetRequiredService<ILoggerFactory>().CreateLogger("DbInitializer");

            try
            {
                var context = services.GetRequiredService<AppDbContext>();
                var config = services.GetRequiredService<IConfiguration>();

                // Garante a existência do banco e das tabelas base
                await context.Database.EnsureCreatedAsync();

                if (context.Database.IsRelational())
                {
                    await ApplyIdempotentSchemaUpdatesAsync(context, logger);
                }

                await SeedUsersAsync(context, config, logger);
            }
            catch (InvalidOperationException)
            {
                throw;
            }
            catch (Exception ex)
            {
                logger.LogError(ex, "Ocorreu um erro ao inicializar o banco de dados.");
            }
        }

