                    ALTER TABLE ""OrdensServico"" ADD COLUMN IF NOT EXISTS ""Prioridade"" integer NOT NULL DEFAULT 0;

                    CREATE TABLE IF NOT EXISTS ""Pecas"" (
                        ""Id"" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
